"""Generates Packages/CandyKit/Sources/DesignSystem/Theme/ThemePalettes.generated.swift from T3's
packages/shared/src/themePalettes.ts: the theme color roles, the standard T3 Code palettes and the built-in
themes (T3 Chat, Grove, Ocean, Ember, Iris).

Usage: /usr/bin/python3 -I scripts/gen-theme-palettes.py [path to the t3code checkout]
The checkout defaults to .t3code-src, then ~/CandyWrapper-research/t3code.
T3_DESIGN_VERSION labels a staged stylesheet update separately from the runtime pin.
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
candidates = sys.argv[1:] or [os.path.join(ROOT, ".t3code-src"), os.path.expanduser("~/CandyWrapper-research/t3code")]
src_root = next(p for p in candidates if os.path.isdir(p))
SRC = open(os.path.join(src_root, "packages/shared/src/themePalettes.ts")).read()
VERSION = os.environ.get("T3_DESIGN_VERSION") or open(os.path.join(ROOT, "T3_VERSION")).read().strip()


def block(name):
    """The object literal assigned to `export const <name>`, parsed as JSON."""
    m = re.search(r"export const " + name + r"(?::[^=]+)? = (\{.*?\n\});", SRC, re.S)
    body = m.group(1)
    body = re.sub(r"//[^\n]*", "", body)
    body = re.sub(r"(\b[A-Za-z_][A-Za-z0-9_]*)\s*:", r'"\1":', body)
    body = re.sub(r",(\s*[}\]])", r"\1", body)
    return json.loads(body)


roles = re.findall(r'"([A-Za-z]+)"', re.search(r"THEME_COLOR_ROLES = \[(.*?)\] as const", SRC, re.S).group(1))
builtins = re.search(r"BUILT_IN_THEMES: ReadonlyArray<ThemeDefinition> = \[(.*?)\];", SRC, re.S).group(1).split(",")
builtins = [b.strip() for b in builtins if b.strip()]


def colors(c):
    for role in c:
        assert role in roles, role
    return "[" + ", ".join(f'.{r}: "{c[r]}"' for r in roles if r in c) + "]"


out = [f"// Generated by scripts/gen-theme-palettes.py from packages/shared/src/themePalettes.ts (T3 {VERSION}). Do not edit.",
       "",
       "/// T3's theme color roles (`THEME_COLOR_ROLES`), in its order.",
       "public enum ThemeColorRole: String, CaseIterable, Sendable, Codable {",
       "    case " + ", ".join(roles),
       "}",
       "",
       "extension ThemeDefinition {"]
for name, label in (("T3_CODE_LIGHT_THEME_COLORS", "standardLight"), ("T3_CODE_DARK_THEME_COLORS", "standardDark")):
    out.append(f"    /// `{name}`: the palette T3 Code wears with no theme installed.")
    out.append(f"    static let {label}Colors: [ThemeColorRole: String] = {colors(block(name))}")
out.append("")
out.append("    /// `BUILT_IN_THEMES`.")
out.append("    public static let builtIns: [ThemeDefinition] = [")
for b in builtins:
    t = block(b)
    variants = t.get("variants", {})
    v = ", ".join(f"ThemeAppearance.{k}: {colors(c)}" for k, c in variants.items())
    out.append(f'        ThemeDefinition(id: "{t["id"]}", label: "{t["label"]}", appearance: .{t["appearance"]},')
    out.append(f"                        colors: {colors(t['colors'])},")
    out.append(f"                        variants: [{v or ':'}], sidebarArtwork: {str(t.get('sidebarArtwork', False)).lower()}),")
out.append("    ]")
out.append("}")
path = os.path.join(ROOT, "Packages/CandyKit/Sources/DesignSystem/Theme/ThemePalettes.generated.swift")
open(path, "w").write("\n".join(out) + "\n")
print("wrote", path, len(roles), "roles,", len(builtins), "built-in themes")
