"""Extract official archive-mode SSH scripts. Does not execute them."""
import pathlib, re, sys
root = pathlib.Path(__file__).resolve().parent.parent
source = pathlib.Path(sys.argv[1] if len(sys.argv)>1 else '/Users/mrm/CandyWrapper-research/t3code/packages/ssh/src/tunnel.ts').read_text()
names = ['REMOTE_RUNNER_SCRIPT','REMOTE_LAUNCH_SCRIPT','REMOTE_PAIRING_SCRIPT','REMOTE_STOP_SCRIPT','REMOTE_PICK_PORT_SCRIPT','REMOTE_WAIT_READY_SCRIPT']
parts = ['// Generated by scripts/gen-ssh-scripts.py from packages/ssh/src/tunnel.ts (MIT).', 'enum SshRemoteScripts {']
for name in names:
    match = re.search(r'(?:export )?const '+name+r' = `((?:\\.|[^`])*)`;',source,re.S)
    value = re.sub(r'\\([\\`$])',r'\1',match.group(1))
    parts += ['    static let '+name+' = #"""',value,'"""#']
parts += ['}']
(root/'Packages/CandyKit/Sources/T3Client/DesktopManaged/SshRemoteScripts.generated.swift').write_text('\n'.join(parts)+'\n')
