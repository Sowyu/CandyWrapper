"""Writes Packages/CandyKit/Sources/Features/PullRequests/GitHubEmoji.generated.swift from T3's
packages/client-runtime/src/githubEmojiAliases.ts (GitHub's gemoji aliases, MIT, Copyright (c) 2019
GitHub, Inc.), one `alias emoji` pair per line, as T3 keeps it.
Usage: /usr/bin/python3 -I scripts/gen-github-emoji.py [t3code checkout, default /tmp/t3code-5258]
"""
import os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
t3 = sys.argv[1] if len(sys.argv) > 1 else "/tmp/t3code-5258"
src = open(os.path.join(t3, "packages/client-runtime/src/githubEmojiAliases.ts"), encoding="utf-8").read()
header, body = src.split("export const GITHUB_EMOJI_ALIASES = `", 1)
body = body.rsplit("`;", 1)[0].strip("\n")
lines = body.split("\n")
for line in lines:
    alias, _, emoji = line.partition(" ")
    assert alias and emoji and "\\" not in line and '"""' not in line, line
notice = "\n".join("/// " + l.removeprefix("//").strip() for l in header.strip().splitlines() if l.startswith("//"))
out = f"""// Generated by scripts/gen-github-emoji.py. Do not edit.
{notice}
// {len(lines)} aliases.

enum GitHubEmojiTable {{
    static let aliases = \"\"\"
{body}
\"\"\"
}}
"""
dest = os.path.join(ROOT, "Packages/CandyKit/Sources/Features/PullRequests/GitHubEmoji.generated.swift")
open(dest, "w", encoding="utf-8").write(out)
print(f"{dest}: {len(lines)} aliases")
