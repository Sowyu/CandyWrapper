#!/usr/bin/env python3
"""Generates the WebSocket RPC method catalog from the T3 contracts.

Usage: scripts/gen-rpc-catalog.py [t3-source-dir] > docs/research/A-rpc-catalog.md

Reads packages/contracts/src/rpc.ts (Rpc.make blocks and the WsRpcGroup member
list), orchestrationV2.ts (ORCHESTRATION_V2_WS_METHODS and its schema table),
clientRpcPermissions.ts and apps/server/src/auth/RpcAuthorization.ts (required
scope per method). Only methods registered in WsRpcGroup are listed; WS_METHODS
also names tags the server does not serve.
"""
import re
import sys
from pathlib import Path

root = Path(sys.argv[1] if len(sys.argv) > 1 else ".t3code-src")
contracts = root / "packages/contracts/src"
rpc = (contracts / "rpc.ts").read_text()
orch = (contracts / "orchestrationV2.ts").read_text()
perms = (contracts / "clientRpcPermissions.ts").read_text()
authz = (root / "apps/server/src/auth/RpcAuthorization.ts").read_text()


def const_table(src: str, name: str) -> dict[str, str]:
    body = re.search(r"export const %s = \{(.*?)\n\} as const;" % name, src, re.S).group(1)
    return dict(re.findall(r'(\w+):\s*"([^"]+)"', body))


ws = const_table(rpc, "WS_METHODS")
ov2 = const_table(orch, "ORCHESTRATION_V2_WS_METHODS")


def resolve_tag(expr: str) -> str:
    expr = expr.strip()
    if expr.startswith("WS_METHODS."):
        return ws[expr.split(".", 1)[1]]
    if expr.startswith("ORCHESTRATION_V2_WS_METHODS."):
        return ov2[expr.split(".", 1)[1]]
    return expr.strip('"')


# Orchestration RPCs refer to OrchestrationV2RpcSchemas.<name>.input/output.
schema_body = re.search(r"export const OrchestrationV2RpcSchemas = \{(.*?)\n\} as const;", orch, re.S).group(1)
orch_schemas = {
    m.group(1): (m.group(2), m.group(3))
    for m in re.finditer(r"(\w+):\s*\{\s*input:\s*([\w.()]+),\s*output:\s*([\w.()]+),?\s*\}", schema_body)
}


def field(block: str, key: str) -> str:
    m = re.search(r"\b%s:\s*" % key, block)
    if not m:
        return ""
    i, depth, out = m.end(), 0, []
    while i < len(block):
        c = block[i]
        if c in "([{":
            depth += 1
        elif c in ")]}":
            if depth == 0:
                break
            depth -= 1
        elif c == "," and depth == 0:
            break
        out.append(c)
        i += 1
    value = " ".join("".join(out).split())
    sm = re.match(r"OrchestrationV2RpcSchemas\.(\w+)\.(input|output)", value)
    if sm and sm.group(1) in orch_schemas:
        value = orch_schemas[sm.group(1)][0 if sm.group(2) == "input" else 1]
    return value


defs = {}
for m in re.finditer(r"const (\w+) = Rpc\.make\(\s*([\w.\"]+),\s*\{(.*?)\n\s*\}\s*,?\s*\);", rpc, re.S):
    var, tag_expr, block = m.group(1), m.group(2), m.group(3)
    defs[var] = {
        "tag": resolve_tag(tag_expr),
        "payload": field(block, "payload") or "{}",
        "success": field(block, "success") or "void",
        "error": field(block, "error"),
        "stream": "stream: true" in block,
    }

group = re.search(r"export const WsRpcGroup = RpcGroup\.make\((.*?)\)\.middleware", rpc, re.S).group(1)
members = re.findall(r"\b(Ws\w+Rpc)\b", group)

# Required scopes: client-guarded table plus the server map. Keys are
# WS_METHODS.x / ORCHESTRATION_V2_WS_METHODS.x or string literals.
scopes: dict[str, str] = {}
for src in (perms, authz):
    for key, scope in re.findall(r"\[((?:WS_METHODS|ORCHESTRATION_V2_WS_METHODS)\.\w+)\]:\s*(\w+)", src):
        scopes[resolve_tag(key)] = scope
scope_names = dict(re.findall(r'export const (Auth\w+Scope) = "([^"]+)"', (contracts / "auth.ts").read_text()))


def scope_of(tag: str) -> str:
    s = scopes.get(tag)
    if s is None:
        return "computed (see RpcAuthorization.ts)"
    return scope_names.get(s, s)


def short(t: str, n: int = 70) -> str:
    t = t.replace("|", "\\|")
    return t if len(t) <= n else t[: n - 1] + "…"


print("# WebSocket RPC catalog (generated)\n")
print(f"Generated by `scripts/gen-rpc-catalog.py` from T3 source at `{root}`. Do not edit by hand.\n")
print(f"{len(members)} methods in `WsRpcGroup`. Unary methods end with an `Exit`. Stream methods send `Chunk`s that the client must `Ack`.\n")
print("| Tag | Kind | Payload | Success | Error | Required scope |")
print("|---|---|---|---|---|---|")
missing = []
for var in members:
    d = defs.get(var)
    if d is None:
        missing.append(var)
        continue
    kind = "stream" if d["stream"] else "unary"
    print(f"| `{d['tag']}` | {kind} | {short(d['payload'])} | {short(d['success'])} | {short(d['error'], 60)} | {scope_of(d['tag'])} |")

unserved = sorted(set(ws.values()) - {defs[v]["tag"] for v in members if v in defs})
print("\n## Names in WS_METHODS that the server does not serve\n")
print(", ".join(f"`{t}`" for t in unserved) or "none")
if missing:
    print("\n## Group members not parsed\n")
    print(", ".join(missing))
