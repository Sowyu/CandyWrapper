#!/usr/bin/env python3
"""Generate EditorIcons.generated.swift: the Open in picker's brand marks that use gradients, masks, filters
or an embedded image, as static SVG documents. T3 draws them from apps/web/src/components/Icons.tsx
(VisualStudioCode, VisualStudioCodeInsiders, VSCodium, AntigravityIcon) and JetBrainsIcons.tsx.
The single-color marks (Cursor, Trae, Kiro, Zed, Finder) stay in scripts/extract-icons.

Usage: scripts/gen-editor-icons.py [--t3 DIR] [--out FILE]
Stdlib only. Re-runnable; output is deterministic.
"""
import argparse, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
ap = argparse.ArgumentParser()
ap.add_argument("--t3", default="/Users/mrm/CandyWrapper-research/t3code")
ap.add_argument("--out", default=os.path.join(ROOT, "Packages/CandyKit/Sources/Features/Thread/EditorIcons.generated.swift"))
args = ap.parse_args()
SRC = os.path.join(args.t3, "apps/web/src/components")

# Editor id -> (file, exported component).
EDITORS = [
    ("vscode", "Icons.tsx", "VisualStudioCode"),
    ("vscode-insiders", "Icons.tsx", "VisualStudioCodeInsiders"),
    ("vscodium", "Icons.tsx", "VSCodium"),
    ("antigravity", "Icons.tsx", "AntigravityIcon"),
    ("idea", "JetBrainsIcons.tsx", "IntelliJIdeaIcon"),
    ("aqua", "JetBrainsIcons.tsx", "AquaIcon"),
    ("clion", "JetBrainsIcons.tsx", "CLionIcon"),
    ("datagrip", "JetBrainsIcons.tsx", "DataGripIcon"),
    ("dataspell", "JetBrainsIcons.tsx", "DataSpellIcon"),
    ("goland", "JetBrainsIcons.tsx", "GoLandIcon"),
    ("phpstorm", "JetBrainsIcons.tsx", "PhpStormIcon"),
    ("pycharm", "JetBrainsIcons.tsx", "PyCharmIcon"),
    ("rider", "JetBrainsIcons.tsx", "RiderIcon"),
    ("rubymine", "JetBrainsIcons.tsx", "RubyMineIcon"),
    ("rustrover", "JetBrainsIcons.tsx", "RustRoverIcon"),
    ("webstorm", "JetBrainsIcons.tsx", "WebStormIcon"),
]

CAMEL = re.compile(r"\b(fillRule|clipRule|stopColor|stopOpacity|colorInterpolationFilters|floodOpacity|clipPath|strokeWidth|"
                   r"strokeLinecap|strokeLinejoin|fillOpacity|strokeOpacity)=")

def kebab(m):
    return re.sub(r"([A-Z])", lambda c: "-" + c.group(1).lower(), m.group(1)) + "="

def component(text, name):
    at = text.index("export const " + name + ":")
    nxt = text.find("\nexport const ", at + 1)
    return text[at:nxt if nxt != -1 else len(text)]

def convert(text, block, name):
    ids = {}
    for var, tmpl in re.findall(r"const (\w+) = `\$\{id\}-([\w-]+)`;", block):
        ids[var] = tmpl
    m = re.search(r"const \[([\w, ]+)\] = useSvgGradientIds\(\"([\w-]+)\", \d+\);", block)
    if m:
        for i, var in enumerate(v.strip() for v in m.group(1).split(",")):
            ids[var] = "%s-%s" % (m.group(2), chr(97 + i))
    svg = block[block.index("<svg"):block.rindex("</svg>") + len("</svg>")]
    svg = svg.replace("{...props}", 'xmlns="http://www.w3.org/2000/svg"')
    svg = re.sub(r'(\w[\w-]*)=\{`url\(#\$\{(\w+)\}\)`\}', lambda m: '%s="url(#%s)"' % (m.group(1), ids[m.group(2)]), svg)
    svg = re.sub(r"id=\{(\w+)\}", lambda m: 'id="%s"' % ids[m.group(1)], svg)
    svg = re.sub(r'style=\{\{\s*mixBlendMode:\s*"([\w-]+)"\s*\}\}', r'style="mix-blend-mode:\1"', svg)
    hm = re.search(r"href=\{(\w+)\}", svg)
    if hm:
        data = re.search(r"const " + hm.group(1) + r"\s*=\s*\"([^\"]+)\"", text).group(1)
        svg = svg.replace(hm.group(0), 'href="%s"' % data)
    svg = CAMEL.sub(kebab, svg)
    if "{" in svg:
        raise SystemExit("unresolved JSX in %s: %s" % (name, re.search(r"\{[^}]*\}", svg).group(0)))
    return re.sub(r"\s+", " ", svg).replace("> <", "><").strip()

out = ["// Generated by scripts/gen-editor-icons.py from T3 Code apps/web/src/components/Icons.tsx and JetBrainsIcons.tsx.",
       "// Do not edit by hand.", "", "enum EditorIconSVG {", "    static let documents: [String: String] = ["]
for editor, file, name in EDITORS:
    text = open(os.path.join(SRC, file), encoding="utf-8").read()
    svg = convert(text, component(text, name), name)
    out.append('        "%s": ###"%s"###,' % (editor, svg))
out += ["    ]", "}", ""]
open(args.out, "w").write("\n".join(out))
print("wrote %d editor icons to %s" % (len(EDITORS), args.out))
